const grpcGeneratedApplicationMarker = "// Code generated by gofly RPC scaffold; application stub is preserved after creation."

func GenerateGRPCScaffold(ctx context.Context, opts GRPCScaffoldOptions) error {
	protoFiles := grpcScaffoldProtoFiles(opts)
	if len(protoFiles) == 0 {
		return errors.New("proto file is required")
	}
	opts.ProtoFile = protoFiles[0]
	if opts.Timeout <= 0 {
		opts.Timeout = 30 * time.Second
	}
	if opts.Dir == "" {
		opts.Dir = "."
	}
	moduleTarget, err := safeRelativeTarget(opts.Dir, "go.mod", "grpc scaffold")
	if err != nil {
		return err
	}
	if err := rejectExistingSymlinkTarget(moduleTarget, "grpc scaffold module"); err != nil {
		return err
	}
	if _, err := os.Stat(moduleTarget); err == nil {
		existing, err := inferModule(opts.Dir)
		if err != nil {
			return err
		}
		if opts.Module != "" && opts.Module != existing {
			return errors.New("scaffold module differs from existing go.mod")
		}
		opts.Module = existing
	} else if !errors.Is(err, os.ErrNotExist) {
		return err
	}
	if opts.Module == "" {
		module, err := inferModule(opts.Dir)
		if err != nil {
			module, err = inferGRPCScaffoldModule(opts)
			if err != nil {
				return err
			}
		}
		opts.Module = module
	}
	if !isSafeProjectFeatureModulePath(opts.Module) {
		return fmt.Errorf("invalid scaffold module %q", opts.Module)
	}
	if err := validateNativeGRPCToolchain(); err != nil {
		return err
	}
	stage, err := os.MkdirTemp("", "gofly-grpc-scaffold-*")
	if err != nil {
		return err
	}
	defer os.RemoveAll(stage)
	protoNames, includes, err := resolveGRPCScaffoldInputs(protoFiles, opts.ProtoPath)
	if err != nil {
		return err
	}
	descriptorPath := filepath.Join(stage, "descriptor.pb")
	if err := GenerateStandardProto(ctx, ProtocOptions{
		ProtoFiles: protoNames, ProtoPath: includes, GoOut: stage, GoGRPCOut: stage, Protoc: opts.Protoc, Timeout: opts.Timeout,
		ExtraArgs: []string{"--go_opt=module=" + opts.Module, "--go-grpc_opt=module=" + opts.Module, "--descriptor_set_out=" + descriptorPath, "--include_imports"},
	}); err != nil {
		return err
	}
	data, err := ReadFileUnderRoot(stage, "descriptor.pb", "grpc descriptors")
	if err != nil {
		return err
	}
	var descriptors descriptorpb.FileDescriptorSet
	if err := proto.Unmarshal(data, &descriptors); err != nil {
		return fmt.Errorf("decode proto descriptors: %w", err)
	}
	plugin, err := (protogen.Options{}).New(&pluginpb.CodeGeneratorRequest{ProtoFile: descriptors.File, FileToGenerate: protoNames})
	if err != nil {
		return fmt.Errorf("resolve proto Go types: %w", err)
	}
	primaryFiles := make([]*protogen.File, 0, len(protoNames))
	serviceCount := 0
	for _, name := range protoNames {
		file := plugin.FilesByPath[name]
		if file == nil {
			return fmt.Errorf("generated proto descriptor %q is missing", name)
		}
		if !strings.HasPrefix(string(file.GoImportPath), opts.Module+"/") {
			return fmt.Errorf("proto %q go_package must be a package under the scaffold module", name)
		}
		primaryFiles = append(primaryFiles, file)
		serviceCount += len(file.Services)
	}
	if serviceCount == 0 {
		return errors.New("proto service is required")
	}
	if opts.RequireMultiple && serviceCount > 1 && !opts.Multiple {
		return errors.New("proto inputs define multiple services; rerun with --multiple")
	}
	if opts.Name == "" {
		opts.Name = strings.TrimSuffix(filepath.Base(opts.ProtoFile), filepath.Ext(opts.ProtoFile))
		if opts.NameFromPackage && strings.TrimSpace(string(primaryFiles[0].Desc.Package())) != "" {
			opts.Name = lowerName(string(primaryFiles[0].Desc.Package()))
		}
	}
	if !token.IsIdentifier(opts.Name) {
		return fmt.Errorf("invalid scaffold name %q", opts.Name)
	}
	if err := migrateLegacyGRPCAdapterDirectory(opts.Dir, opts.Module); err != nil {
		return err
	}
	serverTarget := "internal/api/grpc/v1/register.gen.go"
	serverTargetPath, err := safeRelativeTarget(opts.Dir, serverTarget, "grpc scaffold")
	if err != nil {
		return err
	}
	entries, err := os.ReadDir(filepath.Dir(serverTargetPath))
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	for _, entry := range entries {
		if strings.HasSuffix(entry.Name(), "_grpc.gen.go") && entry.Name() != filepath.Base(serverTargetPath) {
			return errors.New("another grpc scaffold already owns this output root")
		}
	}
	primaryPaths := make(map[string]struct{}, len(primaryFiles))
	for _, file := range primaryFiles {
		primaryPaths[file.Desc.Path()] = struct{}{}
	}
	for _, dependency := range plugin.Files {
		if _, primary := primaryPaths[dependency.Desc.Path()]; primary || !strings.HasPrefix(string(dependency.GoImportPath), opts.Module+"/") {
			continue
		}
		if err := GenerateStandardProto(ctx, ProtocOptions{ProtoFile: dependency.Desc.Path(), ProtoPath: includes, GoOut: stage, GoGRPCOut: stage, Protoc: opts.Protoc, Timeout: opts.Timeout, ExtraArgs: []string{"--go_opt=module=" + opts.Module, "--go-grpc_opt=module=" + opts.Module}}); err != nil {
			return err
		}
	}
	files := make(map[string][]byte)
	if err := filepath.WalkDir(stage, func(path string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if entry.IsDir() || path == descriptorPath {
			return nil
		}
		if !entry.Type().IsRegular() {
			return fmt.Errorf("non-regular protoc output %s", path)
		}
		rel, err := filepath.Rel(stage, path)
		if err != nil {
			return err
		}
		content, err := ReadFileUnderRoot(stage, rel, "protoc output")
		if err != nil {
			return err
		}
		files[rel] = content
		return nil
	}); err != nil {
		return err
	}
	owned := make(map[string]bool)
	if err := renderGRPCScaffold(plugin, primaryFiles, opts, files, owned); err != nil {
		return err
	}
	if err := mergeGRPCScaffoldSharedFiles(opts.Dir, files, owned); err != nil {
		return err
	}
	paths := make([]string, 0, len(files))
	for name, content := range files {
		target, err := safeRelativeTarget(opts.Dir, name, "grpc scaffold")
		if err != nil {
			return err
		}
		if info, err := os.Lstat(target); err == nil {
			if !info.Mode().IsRegular() {
				return fmt.Errorf("grpc scaffold target %q must be a regular file", name)
			}
			if !owned[name] {
				existing, err := ReadFileUnderRoot(opts.Dir, name, "grpc scaffold")
				if err != nil {
					return err
				}
				header, _, _ := strings.Cut(string(content), "\n")
				if !strings.HasPrefix(string(existing), header+"\n") {
					return fmt.Errorf("refusing to overwrite non-generated file %q", name)
				}
				for line := range strings.SplitSeq(string(existing), "\n") {
					if strings.HasPrefix(line, "// source: ") && !strings.Contains(string(content), "\n"+line+"\n") {
						return fmt.Errorf("grpc scaffold output %q belongs to another proto", name)
					}
				}
			}
		} else if !errors.Is(err, os.ErrNotExist) {
			return err
		}
		if filepath.Ext(name) == ".go" {
			formatted, err := format.Source(content)
			if err != nil {
				return fmt.Errorf("format %s: %w", name, err)
			}
			files[name] = formatted
		}
		paths = append(paths, name)
	}
	sort.Strings(paths)
	for _, name := range paths {
		if owned[name] {
			var err error
			if filepath.Clean(name) == filepath.Join("etc", opts.Name+".json") {
				err = mergeGRPCScaffoldJSONDefaults(opts.Dir, name, files[name])
			} else {
				err = writeGeneratedExtensionFile(opts.Dir, name, files[name])
			}
			if err != nil {
				return err
			}
		} else if err := writeGeneratedFileUnder(opts.Dir, name, files[name]); err != nil {
			return err
		}
	}
	return nil
}

func migrateLegacyGRPCAdapterDirectory(root, module string) error {
	rootInfo, err := os.Lstat(root)
	if errors.Is(err, os.ErrNotExist) {
		return nil
	}
	if err != nil {
		return fmt.Errorf("inspect project root before grpc adapter migration: %w", err)
	}
	if !rootInfo.IsDir() || rootInfo.Mode()&os.ModeSymlink != 0 {
		return errors.New("grpc adapter migration root must be a regular directory")
	}
	legacy, err := SafeTarget(root, filepath.Join("internal", "api", "rpc"), "legacy grpc adapter directory")
	if err != nil {
		return err
	}
	target, err := SafeTarget(root, filepath.Join("internal", "api", "grpc"), "grpc adapter directory")
	if err != nil {
		return err
	}
	legacyInfo, err := os.Lstat(legacy)
	if errors.Is(err, os.ErrNotExist) {
		return rewriteLegacyGRPCImports(root, module)
	}
	if err != nil {
		return fmt.Errorf("inspect legacy grpc adapter directory: %w", err)
	}
	if !legacyInfo.IsDir() || legacyInfo.Mode()&os.ModeSymlink != 0 {
		return errors.New("legacy grpc adapter path internal/api/rpc must be a regular directory")
	}
	if _, err := os.Lstat(target); err == nil {
		return errors.New("both internal/api/rpc and internal/api/grpc exist; reconcile them before regenerating")
	} else if !errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("inspect grpc adapter directory: %w", err)
	}
	if err := rejectExistingSymlinkTarget(filepath.Dir(target), "grpc adapter directory parent"); err != nil {
		return err
	}
	if err := os.Rename(legacy, target); err != nil {
		return fmt.Errorf("migrate internal/api/rpc to internal/api/grpc: %w", err)
	}
	return rewriteLegacyGRPCImports(root, module)
}

func rewriteLegacyGRPCImports(root, module string) error {
	oldPrefix := strings.TrimSpace(module) + "/internal/api/rpc"
	newPrefix := strings.TrimSpace(module) + "/internal/api/grpc"
	if oldPrefix == "/internal/api/rpc" {
		return errors.New("module is required to migrate grpc adapter imports")
	}
	return filepath.WalkDir(root, func(path string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if entry.IsDir() || !entry.Type().IsRegular() || filepath.Ext(entry.Name()) != ".go" {
			return nil
		}
		rel, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		data, err := ReadFileUnderRoot(root, rel, "legacy grpc import migration")
		if err != nil {
			return err
		}
		parsed, err := parser.ParseFile(token.NewFileSet(), rel, data, parser.ImportsOnly)
		if err != nil {
			return fmt.Errorf("parse grpc import migration file %s: %w", rel, err)
		}
		type importEdit struct {
			start, end int
			value      string
		}
		edits := make([]importEdit, 0)
		for _, spec := range parsed.Imports {
			pathValue, err := strconv.Unquote(spec.Path.Value)
			if err != nil {
				return fmt.Errorf("decode grpc import in %s: %w", rel, err)
			}
			if pathValue != oldPrefix && !strings.HasPrefix(pathValue, oldPrefix+"/") {
				continue
			}
			edits = append(edits, importEdit{
				start: int(spec.Path.Pos() - 1),
				end:   int(spec.Path.End() - 1),
				value: strconv.Quote(newPrefix + strings.TrimPrefix(pathValue, oldPrefix)),
			})
		}
		if len(edits) == 0 {
			return nil
		}
		for index := len(edits) - 1; index >= 0; index-- {
			edit := edits[index]
			data = append(append(append([]byte(nil), data[:edit.start]...), edit.value...), data[edit.end:]...)
		}
		info, err := os.Stat(path)
		if err != nil {
			return err
		}
		return WriteFileUnderRoot(root, rel, data, info.Mode().Perm(), generatedDirMode, "legacy grpc import migration")
	})
}

func mergeGRPCScaffoldSharedFiles(root string, files map[string][]byte, owned map[string]bool) error {
	splitRPCConfig, err := ReadFileUnderRoot(root, "internal/config/rpc.go", "grpc split config")
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	hasSplitRPCConfig := err == nil &&
		bytes.Contains(splitRPCConfig, []byte("type RPCClientConfig struct")) &&
		bytes.Contains(splitRPCConfig, []byte("func ValidateRPC"))

	for _, item := range []struct {
		path             string
		requiredMarker   string
		rpcMarker        string
		mergeStruct      string
		mergeConstructor string
		renameFunction   map[string]string
	}{
		{path: "internal/config/config.go", requiredMarker: "type OpenAPIConfig struct", rpcMarker: "type RPCClientConfig struct", mergeStruct: "Config", renameFunction: map[string]string{"Validate": "ValidateRPC"}},
		{path: "internal/svc/service_context.go", requiredMarker: "type RPCMuxDiagnosisClient interface", rpcMarker: "type rpcClientResource struct", mergeStruct: "ServiceContext", mergeConstructor: "NewServiceContext"},
	} {
		existing, err := ReadFileUnderRoot(root, item.path, "grpc shared scaffold")
		if errors.Is(err, os.ErrNotExist) {
			continue
		}
		if err != nil {
			return err
		}
		if item.path == "internal/svc/service_context.go" &&
			bytes.Contains(existing, []byte("clientConns")) &&
			bytes.Contains(existing, []byte("InitRPCClients")) {
			files[item.path] = existing
			owned[item.path] = false
			continue
		}
		if item.path == "internal/config/config.go" && hasSplitRPCConfig {
			merged, err := mergeGoScaffoldSplitConfig(existing, files[item.path], splitRPCConfig, item.mergeStruct)
			if err != nil {
				return fmt.Errorf("merge RPC scaffold %s with split RPC config: %w", item.path, err)
			}
			files[item.path] = merged
			owned[item.path] = false
			continue
		}
		if bytes.Contains(existing, []byte(item.rpcMarker)) {
			files[item.path] = existing
			owned[item.path] = false
			continue
		}
		if !bytes.Contains(existing, []byte(item.requiredMarker)) {
			return fmt.Errorf("cannot merge RPC scaffold into user-owned %s", item.path)
		}
		generated := files[item.path]
		if item.path == "internal/svc/service_context.go" {
			generated = bytes.ReplaceAll(generated, []byte("rpcClients"), []byte("grpcClients"))
			generated = bytes.ReplaceAll(generated, []byte("rpcResolvers"), []byte("grpcResolvers"))
		}
		merged, err := mergeGoScaffoldSource(existing, generated, item.mergeStruct, item.mergeConstructor, item.renameFunction)
		if err != nil {
			return fmt.Errorf("merge RPC scaffold %s: %w", item.path, err)
		}
		files[item.path] = merged
		owned[item.path] = false
	}
	return nil
}

func mergeGoScaffoldSource(existing, generated []byte, mergeStruct, mergeConstructor string, renameFunction map[string]string) ([]byte, error) {
	fset := token.NewFileSet()
	base, err := parser.ParseFile(fset, "existing.go", existing, parser.ParseComments)
	if err != nil {
		return nil, err
	}
	addition, err := parser.ParseFile(fset, "generated.go", generated, parser.ParseComments)
	if err != nil {
		return nil, err
	}
	mergeGoImports(base, addition)
	existingNames := goDeclarationNames(base)
	baseStruct := goStructDeclaration(base, mergeStruct)
	additionStruct := goStructDeclaration(addition, mergeStruct)
	if baseStruct == nil || additionStruct == nil {
		return nil, fmt.Errorf("shared struct %s is missing", mergeStruct)
	}
	mergeGoStructFields(baseStruct, additionStruct)
	if mergeConstructor != "" {
		if err := mergeGoConstructor(base, addition, mergeConstructor); err != nil {
			return nil, err
		}
	}
	for _, decl := range addition.Decls {
		if _, ok := decl.(*ast.GenDecl); ok {
			gen := decl.(*ast.GenDecl)
			if gen.Tok == token.IMPORT {
				continue
			}
		}
		name := goDeclarationName(decl)
		if name == mergeStruct || name == mergeConstructor {
			continue
		}
		if replacement := renameFunction[name]; replacement != "" {
			if fn, ok := decl.(*ast.FuncDecl); ok {
				fn.Name.Name = replacement
				name = replacement
			}
		}
		if name != "" {
			if _, exists := existingNames[name]; exists {
				continue
			}
			existingNames[name] = struct{}{}
		}
		base.Decls = append(base.Decls, decl)
	}
	pruneUnusedGoImports(base)
	var output bytes.Buffer
	if err := format.Node(&output, fset, base); err != nil {
		return nil, err
	}
	return output.Bytes(), nil
}

func mergeGoScaffoldSplitConfig(existing, generated, split []byte, mergeStruct string) ([]byte, error) {
	fset := token.NewFileSet()
	base, err := parser.ParseFile(fset, "existing.go", existing, parser.ParseComments)
	if err != nil {
		return nil, err
	}
	addition, err := parser.ParseFile(fset, "generated.go", generated, parser.ParseComments)
	if err != nil {
		return nil, err
	}
	splitFile, err := parser.ParseFile(fset, "split.go", split, parser.ParseComments)
	if err != nil {
		return nil, err
	}
	splitNames := goDeclarationNames(splitFile)
	kept := make([]ast.Decl, 0, len(base.Decls))
	for _, decl := range base.Decls {
		name := goDeclarationName(decl)
		if name != "" && name != mergeStruct {
			if _, duplicate := splitNames[name]; duplicate {
				continue
			}
		}
		kept = append(kept, decl)
	}
	base.Decls = kept
	baseStruct := goStructDeclaration(base, mergeStruct)
	additionStruct := goStructDeclaration(addition, mergeStruct)
	if baseStruct == nil || additionStruct == nil {
		return nil, fmt.Errorf("shared struct %s is missing", mergeStruct)
	}
	addedFields := mergeGoStructFields(baseStruct, additionStruct)
	mergeGoImportsUsedByFields(base, addition, addedFields)
	pruneUnusedGoImports(base)
	var output bytes.Buffer
	if err := format.Node(&output, fset, base); err != nil {
		return nil, err
	}
	return output.Bytes(), nil
}

func pruneUnusedGoImports(file *ast.File) {
	used := make(map[string]struct{})
	ast.Inspect(file, func(node ast.Node) bool {
		selector, ok := node.(*ast.SelectorExpr)
		if !ok {
			return true
		}
		if pkg, ok := selector.X.(*ast.Ident); ok {
			used[pkg.Name] = struct{}{}
		}
		return true
	})
	imports := make([]*ast.ImportSpec, 0, len(file.Imports))
	for _, spec := range file.Imports {
		name := goImportName(spec)
		if name == "_" || name == "." {
			imports = append(imports, spec)
			continue
		}
		if _, ok := used[name]; ok {
			imports = append(imports, spec)
		}
	}
	file.Imports = imports
	for _, decl := range file.Decls {
		gen, ok := decl.(*ast.GenDecl)
		if !ok || gen.Tok != token.IMPORT {
			continue
		}
		specs := make([]ast.Spec, 0, len(gen.Specs))
		for _, raw := range gen.Specs {
			spec, ok := raw.(*ast.ImportSpec)
			if !ok {
				continue
			}
			name := goImportName(spec)
			if name == "_" || name == "." {
				specs = append(specs, spec)
				continue
			}
			if _, ok := used[name]; ok {
				specs = append(specs, spec)
			}
		}
		gen.Specs = specs
	}
}

func goImportName(spec *ast.ImportSpec) string {
	if spec.Name != nil {
		return spec.Name.Name
	}
	name := strings.Trim(spec.Path.Value, "\"")
	if index := strings.LastIndexByte(name, '/'); index >= 0 {
		return name[index+1:]
	}
	return name
}

func mergeGoImports(base, addition *ast.File) {
	existing := make(map[string]struct{}, len(base.Imports))
	for _, spec := range base.Imports {
		existing[goImportKey(spec)] = struct{}{}
	}
	var target *ast.GenDecl
	for _, decl := range base.Decls {
		if gen, ok := decl.(*ast.GenDecl); ok && gen.Tok == token.IMPORT {
			target = gen
			break
		}
	}
	if target == nil {
		target = &ast.GenDecl{Tok: token.IMPORT, Lparen: 1}
		base.Decls = append([]ast.Decl{target}, base.Decls...)
	}
	for _, spec := range addition.Imports {
		if _, exists := existing[goImportKey(spec)]; exists {
			continue
		}
		clone := &ast.ImportSpec{Path: &ast.BasicLit{Kind: token.STRING, Value: spec.Path.Value}}
		if spec.Name != nil {
			clone.Name = ast.NewIdent(spec.Name.Name)
		}
		target.Specs = append(target.Specs, clone)
		base.Imports = append(base.Imports, clone)
		existing[goImportKey(spec)] = struct{}{}
	}
}

func goImportKey(spec *ast.ImportSpec) string {
	name := ""
	if spec.Name != nil {
		name = spec.Name.Name
	}
	return name + "\x00" + spec.Path.Value
}

func goDeclarationNames(file *ast.File) map[string]struct{} {
	names := make(map[string]struct{})
	for _, decl := range file.Decls {
		if name := goDeclarationName(decl); name != "" {
			names[name] = struct{}{}
		}
	}
	return names
}

func goDeclarationName(decl ast.Decl) string {
	switch value := decl.(type) {
	case *ast.FuncDecl:
		if value.Recv == nil || len(value.Recv.List) == 0 {
			return value.Name.Name
		}
		receiver := value.Recv.List[0].Type
		if pointer, ok := receiver.(*ast.StarExpr); ok {
			receiver = pointer.X
		}
		if receiverName, ok := receiver.(*ast.Ident); ok {
			return receiverName.Name + "." + value.Name.Name
		}
	case *ast.GenDecl:
		if len(value.Specs) == 1 {
			if spec, ok := value.Specs[0].(*ast.TypeSpec); ok {
				return spec.Name.Name
			}
		}
	}
	return ""
}

func goStructDeclaration(file *ast.File, name string) *ast.StructType {
	for _, decl := range file.Decls {
		gen, ok := decl.(*ast.GenDecl)
		if !ok {
			continue
		}
		for _, raw := range gen.Specs {
			spec, ok := raw.(*ast.TypeSpec)
			if !ok || spec.Name.Name != name {
				continue
			}
			structure, _ := spec.Type.(*ast.StructType)
			return structure
		}
	}
	return nil
}

func mergeGoStructFields(base, addition *ast.StructType) []*ast.Field {
	existing := make(map[string]struct{})
	for _, field := range base.Fields.List {
		for _, name := range field.Names {
			existing[name.Name] = struct{}{}
		}
	}
	added := make([]*ast.Field, 0)
	for _, field := range addition.Fields.List {
		if len(field.Names) == 0 {
			continue
		}
		if _, ok := existing[field.Names[0].Name]; ok {
			continue
		}
		base.Fields.List = append(base.Fields.List, field)
		added = append(added, field)
		existing[field.Names[0].Name] = struct{}{}
	}
	return added
}

func mergeGoImportsUsedByFields(base, addition *ast.File, fields []*ast.Field) {
	used := make(map[string]struct{})
	for _, field := range fields {
		ast.Inspect(field.Type, func(node ast.Node) bool {
			selector, ok := node.(*ast.SelectorExpr)
			if !ok {
				return true
			}
			if pkg, ok := selector.X.(*ast.Ident); ok {
				used[pkg.Name] = struct{}{}
			}
			return true
		})
	}
	if len(used) == 0 {
		return
	}
	filtered := &ast.File{}
	for _, spec := range addition.Imports {
		name := goImportName(spec)
		if _, ok := used[name]; ok {
			filtered.Imports = append(filtered.Imports, spec)
		}
	}
	mergeGoImports(base, filtered)
}

func mergeGoConstructor(base, addition *ast.File, name string) error {
	baseFn, additionFn := goFunctionDeclaration(base, name), goFunctionDeclaration(addition, name)
	if baseFn == nil || additionFn == nil {
		return fmt.Errorf("shared constructor %s is missing", name)
	}
	baseLiteral, additionLiteral := goReturnedComposite(baseFn), goReturnedComposite(additionFn)
	if baseLiteral == nil || additionLiteral == nil {
		return fmt.Errorf("shared constructor %s must return a struct literal", name)
	}
	existing := make(map[string]struct{})
	for _, element := range baseLiteral.Elts {
		if pair, ok := element.(*ast.KeyValueExpr); ok {
			if key, ok := pair.Key.(*ast.Ident); ok {
				existing[key.Name] = struct{}{}
			}
		}
	}
	added := false
	for _, element := range additionLiteral.Elts {
		pair, ok := element.(*ast.KeyValueExpr)
		if !ok {
			continue
		}
		key, ok := pair.Key.(*ast.Ident)
		if !ok {
			continue
		}
		if _, ok := existing[key.Name]; ok {
			continue
		}
		baseLiteral.Elts = append(baseLiteral.Elts, element)
		added = true
	}
	if added {
		existingStatements := make(map[string]struct{}, len(baseFn.Body.List))
		for _, statement := range baseFn.Body.List {
			existingStatements[goNodeText(statement)] = struct{}{}
		}
		for _, statement := range additionFn.Body.List {
			if _, ok := statement.(*ast.ReturnStmt); !ok {
				if _, exists := existingStatements[goNodeText(statement)]; exists {
					continue
				}
				baseFn.Body.List = append(baseFn.Body.List[:len(baseFn.Body.List)-1], append([]ast.Stmt{statement}, baseFn.Body.List[len(baseFn.Body.List)-1:]...)...)
				existingStatements[goNodeText(statement)] = struct{}{}
			}
		}
	}
	return nil
}

func goNodeText(node ast.Node) string {
	var output bytes.Buffer
	if err := format.Node(&output, token.NewFileSet(), node); err != nil {
		return ""
	}
	return output.String()
}

func goFunctionDeclaration(file *ast.File, name string) *ast.FuncDecl {
	for _, decl := range file.Decls {
		if fn, ok := decl.(*ast.FuncDecl); ok && fn.Recv == nil && fn.Name.Name == name {
			return fn
		}
	}
	return nil
}

func goReturnedComposite(fn *ast.FuncDecl) *ast.CompositeLit {
	for _, statement := range fn.Body.List {
		returned, ok := statement.(*ast.ReturnStmt)
		if !ok || len(returned.Results) == 0 {
			continue
		}
		expr := returned.Results[0]
		if unary, ok := expr.(*ast.UnaryExpr); ok {
			expr = unary.X
		}
		if literal, ok := expr.(*ast.CompositeLit); ok {
			return literal
		}
	}
	return nil
}

func mergeGRPCScaffoldJSONDefaults(root, name string, defaults []byte) error {
	existing, err := ReadFileUnderRoot(root, name, "grpc scaffold config")
	if errors.Is(err, os.ErrNotExist) {
		return writeGeneratedExtensionFile(root, name, defaults)
	}
	if err != nil {
		return err
	}
	target, err := SafeTarget(root, name, "grpc scaffold config")
	if err != nil {
		return err
	}
	info, err := os.Stat(target)
	if err != nil {
		return fmt.Errorf("stat existing grpc scaffold config %s: %w", name, err)
	}
	var currentValues, defaultValues map[string]any
	if err := json.Unmarshal(existing, &currentValues); err != nil {
		return fmt.Errorf("decode existing grpc scaffold config %s: %w", name, err)
	}
	if err := json.Unmarshal(defaults, &defaultValues); err != nil {
		return fmt.Errorf("decode generated grpc scaffold config %s: %w", name, err)
	}
	if !mergeMissingJSONValues(currentValues, defaultValues) {
		return nil
	}
	merged, err := json.MarshalIndent(currentValues, "", "  ")
	if err != nil {
		return fmt.Errorf("encode merged grpc scaffold config %s: %w", name, err)
	}
	return WriteFileUnderRoot(root, name, append(merged, '\n'), info.Mode().Perm(), generatedDirMode, "grpc scaffold config")
}

func mergeMissingJSONValues(current, defaults map[string]any) bool {
	changed := false
	for key, defaultValue := range defaults {
		currentValue, exists := current[key]
		if !exists {
			current[key] = defaultValue
			changed = true
			continue
		}
		currentObject, currentOK := currentValue.(map[string]any)
		defaultObject, defaultOK := defaultValue.(map[string]any)
		if currentOK && defaultOK && mergeMissingJSONValues(currentObject, defaultObject) {
			changed = true
		}
	}
	return changed
}

func inferGRPCScaffoldModule(opts GRPCScaffoldOptions) (string, error) {
	doc, err := ParseProtoFileWithIncludes(opts.ProtoFile, opts.ProtoPath)
	if err != nil {
		return "", fmt.Errorf("infer scaffold module from proto: %w", err)
	}
	goPackage := strings.TrimSpace(protoGoImportPath(doc.GoPackage))
	for _, marker := range []string{"/internal/", "/pkg/"} {
		if index := strings.Index(goPackage, marker); index > 0 {
			return goPackage[:index], nil
		}
	}
	if base := strings.TrimSpace(filepath.Base(goPackage)); goPackage != "" && base != "." && base != string(filepath.Separator) {
		if module := strings.TrimSuffix(goPackage, "/"+base); module != "" {
			return module, nil
		}
	}
	base := lowerName(filepath.Base(filepath.Clean(opts.Dir)))
	if base != "" && base != "." {
		return base, nil
	}
	return "", errors.New("module is required; pass --module or declare option go_package under the project module")
}

