func grpcApplicationDomain(root string, service *protogen.Service) (string, error) {
	candidates := []string{lowerName(strings.TrimSuffix(service.GoName, "Service"))}
	packageName := strings.TrimSpace(string(service.Desc.ParentFile().Package()))
	if packageName != "" {
		candidates = append(candidates, lowerName(strings.Split(packageName, ".")[0]))
	}
	appRoot, err := SafeTarget(root, filepath.Join("internal", "app"), "grpc application domain")
	if err != nil {
		return "", err
	}
	entries, err := os.ReadDir(appRoot)
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return "", fmt.Errorf("read grpc application domains: %w", err)
	}
	bestName, bestMatches, bestCount := "", 0, 0
	for _, entry := range entries {
		if !entry.IsDir() || entry.Type()&os.ModeSymlink != 0 {
			continue
		}
		matches := 0
		for _, method := range service.Methods {
			path := filepath.Join(appRoot, entry.Name(), strings.ToLower(method.GoName)+".go")
			if info, statErr := os.Lstat(path); statErr == nil && info.Mode().IsRegular() {
				matches++
			}
		}
		for _, candidate := range candidates {
			if entry.Name() == candidate && matches > 0 {
				return entry.Name(), nil
			}
		}
		if matches > bestMatches {
			bestName, bestMatches, bestCount = entry.Name(), matches, 1
		} else if matches == bestMatches && matches > 0 {
			bestCount++
		}
	}
	if bestMatches > 0 {
		if bestCount > 1 {
			return "", fmt.Errorf("cannot infer one application domain for RPC service %q: %d directories match its methods", service.Desc.FullName(), bestCount)
		}
		return bestName, nil
	}
	for _, candidate := range candidates {
		if token.IsIdentifier(candidate) {
			return candidate, nil
		}
	}
	return "", fmt.Errorf("cannot derive application domain for RPC service %q", service.Desc.FullName())
}

func readGRPCApplicationContract(root, path, methodName string) (grpcApplicationContract, bool, error) {
	data, err := ReadFileUnderRoot(root, path, "grpc application contract")
	if errors.Is(err, os.ErrNotExist) {
		return grpcApplicationContract{}, false, nil
	}
	if err != nil {
		return grpcApplicationContract{}, false, err
	}
	if bytes.Contains(data, []byte(grpcGeneratedApplicationMarker)) {
		return grpcApplicationContract{}, false, nil
	}
	parsed, err := parser.ParseFile(token.NewFileSet(), path, data, 0)
	if err != nil {
		return grpcApplicationContract{}, false, fmt.Errorf("parse grpc application contract %s: %w", path, err)
	}
	imports := make(map[string]string, len(parsed.Imports))
	for _, spec := range parsed.Imports {
		importPath := strings.Trim(spec.Path.Value, "\"")
		name := filepath.Base(importPath)
		if spec.Name != nil {
			name = spec.Name.Name
		}
		imports[name] = importPath
	}
	for _, decl := range parsed.Decls {
		fn, ok := decl.(*ast.FuncDecl)
		if !ok || fn.Name.Name != methodName || fn.Recv == nil || fn.Type.Results == nil || len(fn.Type.Results.List) == 0 {
			continue
		}
		contract := grpcApplicationContract{}
		if fn.Type.Params != nil && len(fn.Type.Params.List) > 0 {
			importPath, name, ok := grpcContractType(fn.Type.Params.List[0].Type, imports)
			if !ok {
				return grpcApplicationContract{}, false, fmt.Errorf("application method %s in %s must use a named request type", methodName, path)
			}
			contract.RequestImport, contract.RequestType, contract.HasRequest = importPath, name, true
		}
		importPath, name, ok := grpcContractType(fn.Type.Results.List[0].Type, imports)
		if !ok {
			return grpcApplicationContract{}, false, fmt.Errorf("application method %s in %s must return a named response type", methodName, path)
		}
		contract.ResponseImport, contract.ResponseType = importPath, name
		return contract, true, nil
	}
	return grpcApplicationContract{}, false, fmt.Errorf("application file %s does not define method %s", path, methodName)
}

func grpcContractType(expr ast.Expr, imports map[string]string) (string, string, bool) {
	if pointer, ok := expr.(*ast.StarExpr); ok {
		expr = pointer.X
	}
	selector, ok := expr.(*ast.SelectorExpr)
	if !ok {
		return "", "", false
	}
	packageName, ok := selector.X.(*ast.Ident)
	if !ok {
		return "", "", false
	}
	importPath, ok := imports[packageName.Name]
	return importPath, selector.Sel.Name, ok
}

func writeGRPCUnaryApplicationAdapter(server *protogen.GeneratedFile, ident func(string, string) protogen.GoIdent, logicPath string, service *protogen.Service, method *protogen.Method, contract grpcApplicationContract, requestAliases, responseAliases map[string]string) {
	server.P("func (s *", service.GoName, "Server) ", method.GoName, "(ctx ", ident("context", "Context"), ", req *", method.Input.GoIdent, ") (*", method.Output.GoIdent, ", error) {")
	if contract.HasRequest {
		server.P("appReq, err := transcode", service.GoName, "[", ident(contract.RequestImport, contract.RequestType), "](req, ", grpcAliasLiteral(requestAliases), ")")
		server.P("if err != nil { return nil, ", ident("google.golang.org/grpc/status", "Errorf"), "(", ident("google.golang.org/grpc/codes", "InvalidArgument"), ", \"decode ", method.GoName, " request: %v\", err) }")
		server.P("appResp, err := ", ident(logicPath, "New"+method.GoName+"Logic"), "(ctx, s.stx).", method.GoName, "(appReq)")
	} else {
		server.P("appResp, err := ", ident(logicPath, "New"+method.GoName+"Logic"), "(ctx, s.stx).", method.GoName, "()")
	}
	server.P("if err != nil { return nil, ", ident("github.com/imajinyun/gofly/core/errors", "GRPCError"), "(err) }")
	server.P("resp, err := transcode", service.GoName, "[", method.Output.GoIdent, "](appResp, ", grpcAliasLiteral(responseAliases), ")")
	server.P("if err != nil { return nil, ", ident("google.golang.org/grpc/status", "Errorf"), "(", ident("google.golang.org/grpc/codes", "Internal"), ", \"encode ", method.GoName, " response: %v\", err) }")
	server.P("return resp, nil")
	server.P("}")
}

func grpcApplicationAliases(root, module, importPath, typeName string, message *protogen.Message, request bool) (map[string]string, error) {
	if strings.TrimSpace(importPath) == "" || strings.TrimSpace(typeName) == "" {
		return nil, nil
	}
	applicationFields, err := grpcApplicationJSONFields(root, module, importPath, typeName)
	if err != nil {
		return nil, err
	}
	protoFields := make([]string, 0, message.Desc.Fields().Len())
	for index := 0; index < message.Desc.Fields().Len(); index++ {
		protoFields = append(protoFields, message.Desc.Fields().Get(index).JSONName())
	}
	if request {
		return grpcInferAliases(protoFields, applicationFields), nil
	}
	return grpcInferAliases(applicationFields, protoFields), nil
}

func grpcApplicationJSONFields(root, module, importPath, typeName string) ([]string, error) {
	prefix := strings.TrimRight(module, "/") + "/"
	if !strings.HasPrefix(importPath, prefix) {
		return nil, nil
	}
	modelDir := filepath.FromSlash(strings.TrimPrefix(importPath, prefix))
	dir, err := SafeTarget(root, modelDir, "grpc application model")
	if err != nil {
		return nil, err
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, fmt.Errorf("read grpc application model package %s: %w", importPath, err)
	}
	for _, entry := range entries {
		if entry.IsDir() || entry.Type()&os.ModeSymlink != 0 || filepath.Ext(entry.Name()) != ".go" {
			continue
		}
		rel := filepath.Join(modelDir, entry.Name())
		data, err := ReadFileUnderRoot(root, rel, "grpc application model")
		if err != nil {
			return nil, err
		}
		file, err := parser.ParseFile(token.NewFileSet(), rel, data, 0)
		if err != nil {
			return nil, fmt.Errorf("parse grpc application model file %s: %w", rel, err)
		}
		for _, decl := range file.Decls {
			gen, ok := decl.(*ast.GenDecl)
			if !ok {
				continue
			}
			for _, spec := range gen.Specs {
				typeSpec, ok := spec.(*ast.TypeSpec)
				if !ok || typeSpec.Name.Name != typeName {
					continue
				}
				structure, ok := typeSpec.Type.(*ast.StructType)
				if !ok {
					return nil, fmt.Errorf("grpc application model %s.%s must be a struct", importPath, typeName)
				}
				fields := make([]string, 0, len(structure.Fields.List))
				for _, field := range structure.Fields.List {
					if len(field.Names) == 0 || !field.Names[0].IsExported() {
						continue
					}
					name := lowerName(field.Names[0].Name)
					if field.Tag != nil {
						tag := reflect.StructTag(strings.Trim(field.Tag.Value, string(rune(96))))
						if jsonName := strings.Split(tag.Get("json"), ",")[0]; jsonName != "" && jsonName != "-" {
							name = jsonName
						}
					}
					fields = append(fields, name)
				}
				return fields, nil
			}
		}
	}
	return nil, fmt.Errorf("grpc application model %s.%s was not found", importPath, typeName)
}

func grpcInferAliases(source, target []string) map[string]string {
	targetSet := make(map[string]struct{}, len(target))
	for _, name := range target {
		targetSet[strings.ToLower(name)] = struct{}{}
	}
	sourceSet := make(map[string]struct{}, len(source))
	for _, name := range source {
		sourceSet[strings.ToLower(name)] = struct{}{}
	}
	var sourceOnly, targetOnly []string
	for _, name := range source {
		if _, ok := targetSet[strings.ToLower(name)]; !ok {
			sourceOnly = append(sourceOnly, name)
		}
	}
	for _, name := range target {
		if _, ok := sourceSet[strings.ToLower(name)]; !ok {
			targetOnly = append(targetOnly, name)
		}
	}
	if len(sourceOnly) == 1 && len(targetOnly) == 1 {
		return map[string]string{sourceOnly[0]: targetOnly[0]}
	}
	return nil
}

func grpcAliasLiteral(aliases map[string]string) string {
	if len(aliases) == 0 {
		return "nil"
	}
	keys := make([]string, 0, len(aliases))
	for key := range aliases {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	var b strings.Builder
	b.WriteString("map[string]string{")
	for _, key := range keys {
		fmt.Fprintf(&b, "%q:%q,", key, aliases[key])
	}
	b.WriteString("}")
	return b.String()
}
